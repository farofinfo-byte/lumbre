/** Devuelve { id, reflexion, tema } para una fecha (por defecto, hoy en la hora local). */
export function versiculoDelDia(fecha = new Date()) {
  const mes = fecha.getMonth();
  const lista = VERSICULOS[mes];
  const [id, reflexion] = lista[(fecha.getDate() - 1) % lista.length];
  return { id, reflexion, tema: TEMAS[mes] };
}
